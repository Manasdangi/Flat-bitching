export type Scores = {
  clean: number; // cleanliness & upkeep
  safety: number; // women safety: lighting, gated housing, late-night activity
  air: number; // relative air quality (all of Gurgaon is poor in winter)
  market: number; // markets, groceries, malls, restaurants nearby
  green: number; // parks & greenery
  drain: number; // 5 = rarely waterlogged, 1 = floods every monsoon
};

export type Sector = {
  id: string;
  name: string;
  zone: string;
  lat: number;
  lng: number;
  summary: string;
  highlights: string[];
  watchOut: string[];
  societies: string[];
  pg: "High" | "Medium" | "Low";
  rent2bhk: [number, number]; // ₹ thousand / month
  pgRent: [number, number]; // ₹ thousand / month (single occupancy)
  scores: Scores;
};

